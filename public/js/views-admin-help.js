ViewsAdmin.helpDoc = function (view) {
  const content = adminPage(view, "সহায়িকা", "/admin/help");

  const introCard = h("div", { class: "card" });
  introCard.appendChild(h("p", { class: "muted" }, "এডমিন প্যানেলের বিভিন্ন অপশন, সেটিংস এবং টার্মগুলোর সহজ বাংলা ব্যাখ্যা - কোনো টেকনিক্যাল জ্ঞান ছাড়াই বোঝার জন্য। কোনো কিছু পরিবর্তন করলে এন্ড ইউজার (ডোনার/রিকোয়েস্টার)-দের ওপর তার প্রকৃত প্রভাব কী হবে, সেটাও এখানে বলা আছে।"));
  const searchField = h("input", { type: "text", placeholder: "খুঁজুন… (যেমনঃ OTP, পার্জ, লিমিট)" });
  introCard.appendChild(h("div", { class: "field" }, searchField));
  content.appendChild(introCard);

  const sectionsWrap = h("div");
  content.appendChild(sectionsWrap);

  function renderSections(filterText) {
    sectionsWrap.innerHTML = "";
    const q = (filterText || "").trim().toLowerCase();
    let anyMatch = false;

    HELP_DOC_SECTIONS.forEach((section) => {
      const matchingItems = !q
        ? section.items
        : section.items.filter((it) => (it.q + " " + it.a).toLowerCase().includes(q));
      if (!matchingItems.length) return;
      anyMatch = true;

      const details = h("details", { class: "card help-doc-section", open: q ? "" : null });
      const summary = h("summary", { class: "help-doc-section__title" }, [icon(section.icon, "small"), " " + section.title]);
      details.appendChild(summary);

      matchingItems.forEach((it) => {
        const itemBox = h("div", { class: "help-doc-item" });
        itemBox.appendChild(h("div", { class: "help-doc-item__q" }, it.q));
        itemBox.appendChild(h("div", { class: "help-doc-item__a", html: it.a }));
        details.appendChild(itemBox);
      });

      sectionsWrap.appendChild(details);
    });

    if (!anyMatch) {
      sectionsWrap.appendChild(h("div", { class: "card center muted" }, "কোনো ফলাফল পাওয়া যায়নি।"));
    }
  }

  renderSections("");
  searchField.oninput = () => renderSections(searchField.value);
};
